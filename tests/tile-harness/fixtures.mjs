/* ---------------------------------------------------------------- *
 * 1. 网络错误
 * ---------------------------------------------------------------- */

export const NETWORK_ERRORS = {
  timeout: "The request timed out",
  /** Stash 实际会抛的典型错误 */
  refused: "Could not connect to the server.",
  dns: "A server with the specified hostname could not be found.",
  /** 通过不存在/未配置的代理节点 */
  proxy: "The proxy server is not functioning properly.",
}

/** 构造网络错误夹具；不传则用 refused */
export function networkError(message = NETWORK_ERRORS.refused) {
  return { error: message }
}

/** 构造"请求永不回调"夹具 */
export function hang() {
  return { hang: true }
}

