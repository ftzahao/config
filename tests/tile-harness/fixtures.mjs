/**
 * 夹具库：模拟真实网络环境下的各种响应形态。
 *
 * 所有夹具都是"纯函数"或常量对象，可直接放进 `responses` 数组：
 *   { status, headers, body }       成功响应
 *   { error: "..." }                网络错误（连接失败 / 超时 / DNS）
 *   { hang: true }                  请求发出但永不回调（模拟被黑洞的请求）
 *   (params, index) => item         函数形式，可按 URL 断言（用于多请求脚本，如 netflix / disney）
 *
 * 覆盖任务要求的六类边界：
 *   1. 网络错误                networkError()
 *   2. HTML 拦截页             cloudflareHtml() —— 《Just a moment...》
 *   3. 204 空响应              noContent()
 *   4. 301 / 302 重定向        redirect()
 *   5. JSON 解析失败           brokenJson()
 *   6. 回调永不返回            hang()
 */

