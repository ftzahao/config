/** 429 限流（带 Retry-After） */
export function rateLimited(headers = { "Retry-After": "60" }) {
  return { status: 429, headers, body: "" }
}

/** 5xx 网关错误页 */
export function serverError(status = 502) {
  return { status, headers: { "Content-Type": "text/html" }, body: "<html><body>502 Bad Gateway</body></html>" }
}

